/// UV rect for an icon (icons live in the region below the glyph block).
pub fn icon_rect(id: IconId) -> [f32; 4] {
    let i = id as u32;
    let col = i % ICON_COLS;
    let row = i / ICON_COLS;
    let x0 = col * ICON_W;
    let y0 = GLYPH_REGION_H + row * ICON_H;
    [
        x0 as f32 / ATLAS_W as f32,
        y0 as f32 / ATLAS_H as f32,
        (x0 + ICON_W) as f32 / ATLAS_W as f32,
        (y0 + ICON_H) as f32 / ATLAS_H as f32,
    ]
}

/// UV rect (u0,v0,u1,v1) for ASCII char `c`. Returns `[0,0,0,0]` for chars
/// outside the printable range (treated as zero-width / skipped).
pub fn glyph_rect(c: char) -> [f32; 4] {
    let cu = c as u32;
    if !(0x20..0x80).contains(&cu) {
        return [0.0; 4];
    }
    let idx = cu - 0x20;
    let col = idx % COLS;
    let row = idx / COLS;
    let u0 = (col * GLYPH_W) as f32 / ATLAS_W as f32;
    let v0 = (row * GLYPH_H) as f32 / ATLAS_H as f32;
    let u1 = u0 + (GLYPH_W as f32 / ATLAS_W as f32);
    let v1 = v0 + (GLYPH_H as f32 / ATLAS_H as f32);
    [u0, v0, u1, v1]
}

