/// Generate the full font atlas as 8-bit alpha bytes (ATLAS_W * ATLAS_H).
/// Expands FONT_DATA bit patterns into per-pixel alpha values.
pub fn bake_atlas() -> thin_vec::ThinVec<u8> {
    let mut out = thin_vec::ThinVec::with_capacity((ATLAS_W * ATLAS_H) as usize);
    out.resize((ATLAS_W * ATLAS_H) as usize, 0u8);
    for (char_idx, glyph) in FONT_DATA.iter().enumerate() {
        let col = char_idx as u32 % COLS;
        let row = char_idx as u32 / COLS;
        let x0 = col * GLYPH_W;
        let y0 = row * GLYPH_H;
        for (gy, &row_bits) in glyph.iter().enumerate() {
            for gx in 0..GLYPH_W {
                if (row_bits >> (GLYPH_W - 1 - gx)) & 1 != 0 {
                    let off = ((y0 + gy as u32) * ATLAS_W + x0 + gx) as usize;
                    out[off] = 0xFF;
                }
            }
        }
    }
    out
}
